export const meta = {
  name: 'single-paper-review',
  description: '单篇文献深度研读工作流 - 提取内容、批判性分析、质量评审、生成知识卡片',
  phases: [
    { title: '内容解析', detail: '提取文献元数据、核心方法、实验数据' },
    { title: '深度分析', detail: '批判性分析方法论、识别创新点和局限' },
    { title: '质量评审', detail: '独立评审知识卡片的完整性、准确性、深度' },
    { title: '项目映射', detail: '分析与本项目的关联，提炼借鉴要点' },
  ],
};

// ============================================================
// 使用说明：
// 在调用时通过 args 传入文献内容，格式：
// { "paper_content": "论文全文或摘要...", "paper_type": "期刊/学位/综述" }
// ============================================================

const PROJECT_CONTEXT = '基于深度强化学习的多无人机协同物流配送路径规划';

const PAPER_CONTENT = args?.paper_content || '请在args中提供论文内容';
const PAPER_TYPE = args?.paper_type || '期刊';

// Phase 1: 内容解析
phase('内容解析');

const parsed = await agent(
  `你是学术文献内容解析专家。

项目背景：${PROJECT_CONTEXT}

请对以下${PAPER_TYPE}论文进行结构化内容提取：

${PAPER_CONTENT}

## 提取要求

### 1. 元数据层
| 项目 | 内容 |
|------|------|
| 标题（中文） | |
| 标题（英文） | |
| 作者 | |
| 机构 | |
| 年份 | |
| 期刊/会议 | |
| DOI | |
| 关键词 | |

### 2. 概念层
- **核心问题**：[用一句话精确描述]
- **研究动机**：[为什么这个问题重要？现有方法的不足？]
- **问题形式化**：[数学描述]
- **核心假设**：[列出关键假设]

### 3. 方法层
- **技术路线**：[3-5句概述]
- **关键创新点**：[逐条列出，与现有方法的区别]
- **核心公式**：[LaTeX格式，含变量说明]
- **算法流程**：[伪代码或步骤描述]
- **模型架构**：[如适用，描述网络结构]

### 4. 验证层
- **实验环境/数据集**：
- **基线方法**：
- **评价指标**：
- **核心结果**：[表格化]
- **消融实验**：[各组件贡献]

### 5. 价值层
- **主要贡献**：[列出]
- **局限性**：[列出]
- **未来方向**：[列出]

输出格式：结构化Markdown，公式用LaTeX，数据用表格。`,
  { label: '内容解析', phase: '内容解析' }
);

log('内容解析完成');

// Phase 2: 深度分析
phase('深度分析');

const analysis = await agent(
  `你是学术文献批判性分析专家。

项目背景：${PROJECT_CONTEXT}

基于以下文献解析结果，请进行深度批判性分析：

${parsed}

## 分析框架

### 1. 方法论分析
- 技术路线的逻辑性评估
- 算法设计的合理性分析
- 与现有方法的本质区别
- 理论保证（收敛性、复杂度）

### 2. 创新性评估
- 创新的实质性程度（突破性/渐进性/增量性）
- 创新的可重复性
- 创新的普适性

### 3. 实验验证评估
- 实验设计的科学性
- 基线选择的公平性
- 消融实验的完整性
- 结果的可重复性

### 4. 潜在问题识别
- 方法的潜在缺陷
- 隐含假设的合理性
- 未讨论的边界情况
- 可能的失效场景

### 5. 深度思考
- 这篇论文的核心洞察是什么？
- 如果继续改进，方向是什么？
- 最值得借鉴的是什么？

输出要求：
- 每个分析点都要有依据
- 标注置信度：[高/中/低]
- 标注存疑点：[需进一步验证]`,
  { label: '深度分析', phase: '深度分析' }
);

log('深度分析完成');

// Phase 3: 质量评审
phase('质量评审');

const review = await agent(
  `你是文献研读质量评审专家。

请对以下知识卡片进行独立质量评审：

## 解析结果
${parsed}

## 分析结果
${analysis}

## 评审标准

### A. 完整性（满分30分）
- 基本信息完整（5分）
- 研究问题清晰（5分）
- 核心方法提取完整（5分）
- 关键公式正确（5分）
- 实验结果完整（5分）
- 创新点识别（5分）

### B. 准确性（满分30分）
- 技术描述准确（10分）
- 数据引用正确（10分）
- 结论有依据（10分）

### C. 深度（满分25分）
- 理解方法本质创新（10分）
- 批判性分析到位（8分）
- 局限性识别（7分）

### D. 关联性（满分15分）
- 与本项目关联具体（8分）
- 借鉴要点可操作（7分）

## 输出格式

### 评分汇总
| 维度 | 得分 | 满分 |
|------|------|------|
| 完整性 | /30 | 30 |
| 准确性 | /30 | 30 |
| 深度 | /25 | 25 |
| 关联性 | /15 | 15 |
| **总分** | **/100** | **100** |

### 等级判定
A（≥85）：优秀 | B（70-84）：良好 | C（60-69）：合格 | D（<60）：不合格

### 问题清单
[列出发现的问题]

### 改进建议
[列出改进建议]

### 评审结论
通过 / 修订 / 重做`,
  { label: '质量评审', phase: '质量评审' }
);

log(`质量评审完成: ${review?.match(/总分.*?(\d+)/)?.[1] || 'N/A'}分`);

// Phase 4: 项目映射
phase('项目映射');

const mapping = await agent(
  `你是项目技术映射专家。

项目背景：${PROJECT_CONTEXT}
项目模块：
- 环境建模：状态空间、动作空间、仿真环境设计
- 奖励函数设计：能耗奖励、时间奖励、协同奖励、安全约束
- 算法选择：MARL算法（MAPPO/MADDPG/QMIX等）
- 任务分配：匈牙利算法/拍卖算法/注意力模型

基于以下文献研读结果，请分析与本项目的关联：

## 解析结果
${parsed}

## 分析结果
${analysis}

## 输出要求

### 1. 项目模块映射
| 项目模块 | 关联度 | 具体关联说明 | 可借鉴内容 |
|---------|--------|-------------|-----------|
| 环境建模 | ★/★★/★★★ | | |
| 奖励设计 | ★/★★/★★★ | | |
| 算法选择 | ★/★★/★★★ | | |
| 任务分配 | ★/★★/★★★ | | |

### 2. 可借鉴要点（按优先级排序）
1. **[要点1]**
   - 具体内容：
   - 应用场景：
   - 实施方案：
   - 预期效果：
   - 实施难度：高/中/低

2. **[要点2]**
   ...

### 3. 需要注意的差异
- [差异1：本项目与论文场景的不同]
- [差异2]

### 4. 实施建议
- 短期可直接采用的：
- 需要适配后使用的：
- 长期可探索的：`,
  { label: '项目映射', phase: '项目映射' }
);

log('项目映射完成');

// 最终整合
const finalCard = `# 知识卡片

${parsed}

---

## 批判性分析

${analysis}

---

## 项目映射

${mapping}

---

## 质量评审

${review}

---
*生成日期: ${new Date().toISOString().split('T')[0]}*
*工作流: single-paper-review v2.0*`;

return {
  parsed,
  analysis,
  review,
  mapping,
  finalCard,
};
